#!/usr/bin/env python3
"""
Run the reasoning-capability query suite (Q1-Q9) against Apache Jena Fuseki,
one dataset per Jena reasoner, and compare the results side by side.

This is the Fuseki counterpart of ../../graphdb/code/run_reasoning_tests.py and
uses the same inputs (../../graphdb/data/university.ttl, queries.rq), the same
query parsing and the same result normalisation, so the two reports can be
compared row by row.

How Fuseki differs from GraphDB:
  - Inference is configured per dataset in an assembler file, by wrapping the
    data in a ja:InfModel with a Jena reasoner. This script generates that
    file (results/fuseki-config.ttl), one dataset per reasoner, each loading
    the test data into memory at start-up.
  - Jena reasoners are rule-based but not materialised in the store: they run
    in memory (forward + backward chaining) when the dataset is first queried.
  - There is no onto:implicit pseudo-graph, so Q10 is skipped here; the
    implicit-triple counts come from JenaReasoners.java instead.
  - Consistency is not checked on load; it needs InfModel.validate(), which
    Fuseki does not expose. JenaReasoners.java runs it.

Usage:
  # 1. let the script start Fuseki (path to the fuseki-server script or jar)
  python run_fuseki_tests.py --fuseki ~/opt/apache-jena-fuseki-5.6.0/fuseki-server
  python run_fuseki_tests.py --fuseki ~/opt/jena-fuseki-server-5.6.0.jar

  # 2. or start it yourself with the generated config, then query it
  python run_fuseki_tests.py --config-only
  fuseki-server --config=../results/fuseki-config.ttl --port=3030
  python run_fuseki_tests.py

  python run_fuseki_tests.py --reasoners none rdfs owl-micro --only Q1 Q2
  python run_fuseki_tests.py --data other.ttl --fuseki ...

Writes ../results/fuseki_reasoning_report.md (+ .json).
Standard library only.
"""
import argparse
import json
import subprocess
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS_DIR = HERE.parent / "results"
GRAPHDB_DIR = HERE.parents[1] / "graphdb"
DATA_DIR = GRAPHDB_DIR / "data"          # shared test inputs
sys.path.insert(0, str(GRAPHDB_DIR / "code"))
from run_reasoning_tests import parse_queries, prefix_map, normalise, fmt_rows  # noqa: E402

JENA = "http://jena.hpl.hp.com/2003/"
# dataset name -> (reasoner URL or None, description)
REASONERS = {
    "none":       (None, "no reasoner (explicit triples only)"),
    "transitive": (JENA + "TransitiveReasoner", "subClassOf / subPropertyOf closure only"),
    "rdfs":       (JENA + "RDFSExptRuleReasoner", "RDFS rule reasoner"),
    "owl-micro":  (JENA + "OWLMicroFBRuleReasoner", "RDFS + some OWL (inverse, transitive, symmetric, equivalence, intersection, hasValue)"),
    "owl-mini":   (JENA + "OWLMiniFBRuleReasoner", "OWL rules without bNode-creating rules (minCardinality, someValuesFrom)"),
    "owl":        (JENA + "OWLFBRuleReasoner", "full Jena OWL rule set (OWL Lite + part of OWL DL)"),
    "compiled":   (JENA + "GenericRuleReasoner", "rule profile compiled from the ontology "
                                                 "(jena-rule-profile/code/compile_rules.py)"),
}
COMPILER = HERE.parents[2] / "jena-rule-profile" / "code" / "compile_rules.py"
SPARQL_JSON = "application/sparql-results+json"


# ------------------------------------------------------------------ config file
def config_ttl(reasoners, data_files, rules=None):
    content = " ,\n            ".join(
        f"[ ja:externalContent <{Path(f).resolve().as_uri()}> ]" for f in data_files)
    out = [
        "PREFIX :       <#>",
        "PREFIX fuseki: <http://jena.apache.org/fuseki#>",
        "PREFIX rdf:    <http://www.w3.org/1999/02/22-rdf-syntax-ns#>",
        "PREFIX ja:     <http://jena.hpl.hp.com/2005/11/Assembler#>",
        "",
        "## Generated by run_fuseki_tests.py: one dataset per Jena reasoner,",
        "## each loading the test data into memory at start-up.",
        "",
        "[] rdf:type fuseki:Server .",
        "",
        ":base a ja:MemoryModel ;",
        f"    ja:content {content} .",
    ]
    for name in reasoners:
        url, desc = REASONERS[name]
        sid = name.replace("-", "_")
        out += [
            "",
            f"## {name}: {desc}",
            f":svc_{sid} a fuseki:Service ;",
            f'    fuseki:name "{name}" ;',
            '    fuseki:endpoint [ fuseki:operation fuseki:query ; fuseki:name "sparql" ] ;',
            f"    fuseki:dataset :ds_{sid} .",
            f":ds_{sid} a ja:RDFDataset ;",
        ]
        if url is None:
            out.append("    ja:defaultGraph :base .")
        else:
            out += [
                f"    ja:defaultGraph :inf_{sid} .",
                f":inf_{sid} a ja:InfModel ;",
                "    ja:baseModel :base ;",
                f"    ja:reasoner [ ja:reasonerURL <{url}> ] ." if name != "compiled" else
                f"    ja:reasoner [ ja:reasonerURL <{url}> ; ja:rulesFrom <{Path(rules).resolve().as_uri()}> ] .",
            ]
    return "\n".join(out) + "\n"


# ------------------------------------------------------------------------ HTTP
def http_post(url, data, timeout=300):
    req = urllib.request.Request(url, data=data, method="POST", headers={
        "Accept": SPARQL_JSON, "Content-Type": "application/x-www-form-urlencoded"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return r.status, r.read().decode("utf-8")
    except urllib.error.HTTPError as e:
        return e.code, e.read().decode("utf-8", errors="replace")
    except urllib.error.URLError as e:
        return None, str(e.reason)


def wait_for(base, proc, timeout=120):
    t0 = time.time()
    while time.time() - t0 < timeout:
        if proc is not None and proc.poll() is not None:
            sys.exit(f"Fuseki exited with code {proc.returncode}; see {RESULTS_DIR / 'fuseki.log'}")
        try:
            with urllib.request.urlopen(f"{base}/$/ping", timeout=2):
                return
        except Exception:
            time.sleep(1)
    sys.exit(f"Fuseki not reachable at {base} after {timeout}s")


def start_fuseki(fuseki, config, port):
    fuseki = Path(fuseki).expanduser()
    if fuseki.suffix == ".jar":
        cmd = ["java", "-jar", str(fuseki)]
    else:
        cmd = [str(fuseki)]
    cmd += [f"--config={config}", f"--port={port}"]
    log = open(RESULTS_DIR / "fuseki.log", "w")
    print("Starting:", " ".join(cmd))
    return subprocess.Popen(cmd, stdout=log, stderr=subprocess.STDOUT)


# ------------------------------------------------------------------------ main
def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--fuseki", help="fuseki-server script or jena-fuseki-server-*.jar; "
                                     "if omitted, Fuseki must already be running with the generated config")
    ap.add_argument("--port", type=int, default=3030)
    ap.add_argument("--reasoners", nargs="*", default=list(REASONERS), choices=list(REASONERS))
    ap.add_argument("--rules", help="rule profile for the 'compiled' dataset (default: compiled from --data "
                                    "with compile_rules.py --sameas into ../results/compiled.rules)")
    ap.add_argument("--data", nargs="*", default=[str(DATA_DIR / "university.ttl")])
    ap.add_argument("--queries", default=str(DATA_DIR / "queries.rq"))
    ap.add_argument("--only", nargs="*", help="query ids to run (default: all except Q10)")
    ap.add_argument("--config-only", action="store_true", help="write the Fuseki config and stop")
    ap.add_argument("--report", default=str(RESULTS_DIR / "fuseki_reasoning_report.md"))
    args = ap.parse_args()

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    config = RESULTS_DIR / "fuseki-config.ttl"
    if "compiled" in args.reasoners and not args.rules:
        # the test KG has schema and data in one file: compile the profile from it,
        # with the sameAs rules, so that it is comparable with GraphDB owl2-rl
        args.rules = str(RESULTS_DIR / "compiled.rules")
        cmd = [sys.executable, str(COMPILER), *args.data, "-o", args.rules, "--sameas"]
        print("Compiling the rule profile:", " ".join(cmd[2:]))
        if subprocess.run(cmd).returncode != 0:
            sys.exit("compile_rules.py failed")
    config.write_text(config_ttl(args.reasoners, args.data, args.rules), encoding="utf-8")
    print(f"Fuseki config written to {config}")
    if args.config_only:
        return

    base = f"http://localhost:{args.port}"
    proc = start_fuseki(args.fuseki, config, args.port) if args.fuseki else None
    try:
        wait_for(base, proc)
        run_suite(args, base)
    finally:
        if proc is not None:
            proc.terminate()
            proc.wait(timeout=30)


def check_datasets(base, reasoners, config):
    """Fail early if the running Fuseki does not serve the generated datasets."""
    missing = []
    for r in reasoners:
        status, body = http_post(f"{base}/{r}/sparql",
                                 urllib.parse.urlencode({"query": "ASK {}"}).encode(), timeout=600)
        if status != 200:
            missing.append(f"{r} (HTTP {status})")
    if missing:
        sys.exit(
            f"The Fuseki at {base} does not serve these datasets: {', '.join(missing)}.\n"
            "It was probably started without the generated configuration. Either stop it and run\n"
            "  python code/run_fuseki_tests.py --fuseki <path>/fuseki-server\n"
            "or restart it with\n"
            f"  <path>/fuseki-server --config={config}")


def run_suite(args, base):
    check_datasets(base, args.reasoners, RESULTS_DIR / "fuseki-config.ttl")
    queries, prefix_block = parse_queries(args.queries)
    wanted = set(args.only) if args.only else {q for q in queries if q != "Q10"}
    queries = {k: v for k, v in queries.items() if k in wanted}
    pmap = prefix_map(prefix_block)
    pmap.setdefault("http://www.w3.org/1999/02/22-rdf-syntax-ns#", "rdf")
    pmap.setdefault("http://www.w3.org/2001/XMLSchema#", "xsd")

    md = ["# Fuseki reasoning report\n", f"Endpoint: `{base}` · data: "
          + ", ".join(f"`{Path(d).name}`" for d in args.data) + "\n",
          "| Dataset | Reasoner |", "|---|---|"]
    md += [f"| {r} | {REASONERS[r][0] or '–'} |" for r in args.reasoners]
    dump = {}

    for qid, (title, sparql, body_only) in queries.items():
        print(f"\n=== {qid} {title}")
        md += [f"\n## {qid} — {title}\n", "```sparql", body_only, "```\n",
               "| Dataset | #rows | Time (s) | Result |", "|---|---|---|---|"]
        results = {}
        for r in args.reasoners:
            t0 = time.time()
            status, body = http_post(f"{base}/{r}/sparql",
                                     urllib.parse.urlencode({"query": sparql}).encode())
            dt = time.time() - t0
            if status != 200:
                err = f"HTTP {status}: {body[:200].strip()}"
                results[r] = ("ERROR", err)
                print(f"  {r:12} ERROR {err}")
                md.append(f"| {r} | – | {dt:.2f} | ERROR: {err} |")
                continue
            vars_, rows = normalise(json.loads(body), pmap)
            results[r] = (vars_, rows)
            text = fmt_rows(vars_, rows)
            print(f"  {r:12} [{len(rows):>3}] {dt:6.2f}s {text}")
            md.append(f"| {r} | {len(rows)} | {dt:.2f} | {text.replace('|', chr(92) + '|')} |")

        ok = {r: set(v[1]) for r, v in results.items() if v[0] != "ERROR"}
        if ok:
            union = set().union(*ok.values())
            md.append("")
            for r, rows in ok.items():
                missing = sorted(union - rows)
                if missing:
                    line = fmt_rows(results[r][0], missing)
                    print(f"  ↳ {r} missing: {line}")
                    md.append(f"- **{r}** missing: {line}")
        dump[qid] = {r: (v if v[0] == "ERROR" else {"vars": v[0], "rows": v[1]})
                     for r, v in results.items()}

    md.append("\nThe first query against each dataset includes the reasoner's start-up "
              "(rule engine preparation), so its time is not comparable with the others.")
    Path(args.report).write_text("\n".join(md) + "\n", encoding="utf-8")
    Path(args.report).with_suffix(".json").write_text(json.dumps(dump, indent=2), encoding="utf-8")
    print(f"\nReport written to {args.report} (+ .json)")


if __name__ == "__main__":
    main()
